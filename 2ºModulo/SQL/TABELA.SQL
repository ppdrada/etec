CREATE DATABASE BRASIL;
USE BRASIL;

CREATE TABLE REGIOES
 (RGSCODIGO INT auto_increment PRIMARY KEY,
  RGSNOME VARCHAR(30));
  
CREATE TABLE ESTADOS
 (STDUF CHAR(2) PRIMARY KEY,
  STDCIDADE VARCHAR(50) NOT NULL,
  STDCAPITAL VARCHAR(100),
  STDREGIAO INT,
  STDPOPULACAO NUMERIC(10),
  CONSTRAINT FOREIGN KEY (STDREGIAO) REFERENCES REGIOES(RGSCODIGO));
  
  select * from REGIOES;
  
  select * from ESTADOS;
