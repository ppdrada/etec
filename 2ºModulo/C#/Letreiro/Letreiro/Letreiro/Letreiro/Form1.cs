        private void fnRolarTexto(int nPosInicial) //Procedimento que fara a rolagem do texto exibido com um parametro do tipo inteiro
        {
            byte[,] vLetra; //declarando um vetor do tipo byte, cuidado a variavel do metod fnLetras e diferente desse                
            Color[] oCorFundo = { Color.FromArgb(50,objCor.Color), objCor.Color }; //declarando um vetor para trocar a cor do letreiro. O numero que esta na freste do primeiro metodo é a intencidade da cor de fundo.  
            int nPosicao = nPosInicial; //declarando uma variável do tipo inteiro que está guardando a variável que foi passada como parâmentro 
            int nTamanho = (int)(imgLetras.Height / 7); //declarando uma variável que guarda o valor da altura do mapa dividido por 7 que é numero de coluna e linha se fosse outro numero iria corta uma circulo e está convertidos para inteiro

            oLetras.Clear(Color.Black);//Limpa o letrier com a cor preta.
            //Se a posição é menor que o numero da matriz do texto que está sento mostrado  
            while (nPosicao < (cTexto + " " + cTexto).Length)// Posição das letras que será exibido e está como o  Length propriedade para obter o número total de elementos em uma matriz.
            {
                vLetra = fnLetras((cTexto + " " + cTexto)[nPosicao]);//guardado dentro da variavel a mensagem mostrada e a posição
                for (int nAux = 0; nAux <= vLetra.GetUpperBound(1); nAux++)//variavel que ira auxiliar nas letras exbidadas GetUpperBound métodos para exibir os limites de uma matriz
                {//Se o limite do vetor for maior que a variavel auxiliadora que é 0 entra só irá para quando for Igual 
                    for (int nCont = 0; nCont <= vLetra.GetUpperBound(0); nCont++)// Se o limite do vetor for maior que a variavel auxiliadora que é 0 entra só irá para quando for Igual
                          oLetras.FillEllipse( new SolidBrush(oCorFundo[vLetra[nCont, nAux]]), x: nAux * nTamanho +(nPosicao - nPosInicial) * (nTamanho * 7), y: nCont * nTamanho, width: nTamanho - 1, height: nTamanho - 1);
                   //Imagem grafica que irá ser exbida no PictureBox/ SolidBrush, que é um pincel de uma única cor, tendo como parametro a cor que já foi definida e dentro o vetro das letra e dentro do Vetor a Posições de Largura e Altura
                    //o Aux e o Cont servem somente para que uma bolinha não fique um encima da outra quando exibir o nPosicao é para fazer a rolagem do letreiro não sei muito bem como ele funciona só sei que sem ele não funciona 
                }
                nPosicao++;// somando mais um a posição até que a posião seja igual ao texto que está sendo exibido
            }
            //depois de sair do while/enquanto irá
            imgLetras.Refresh(); // exibindo o Atualizar o PictureBox com o novo texto digitado
        }

        private void objTempo_Tick(object sender, EventArgs e)
        {
            if (Convert.ToInt32(objTempo.Tag) < cTexto.Length) //Covertou a Time para inteiro com um sinal de 32 bit e esta tendado se é menor que quantidade de matrizes 
                fnRolarTexto(Convert.ToInt32(objTempo.Tag));// se for o letreiro vai rolar convorme o objTempo
            else
            {
                objTempo.Tag = -1;//Tavalendo -1 agora
                oLetras.Clear(Color.Black);//Limpar tela
                imgLetras.Refresh();//Atualiza
            }
            objTempo.Tag = Convert.ToInt32(objTempo.Tag) + 1;
        }

