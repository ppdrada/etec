CREATE DATABASE MERCADO;
	USE MERCADO;
    
CREATE TABLE CATEGORIAS(
	CTG_CODIGO int AUTO_INCREMENT,
    CTG_DESCRICAO varchar(50) NOT NULL,
    PRIMARY KEY (CTG_CODIGO)
);

CREATE TABLE FORNECEDORES(
	FRN_CODIGO int AUTO_INCREMENT,
    FRN_NOME varchar(150) NOT NULL,
    PRIMARY KEY (FRN_CODIGO)
);

CREATE TABLE PRODUTOS(
	PRD_CODIGO int AUTO_INCREMENT,
    PRD_NOME varchar(150) NOT NULL,
    PRD_DESCRICAO text,
    PRD_CATEG int,
    PRD_FORN int,
    PRD_BLOQUEIO bit,
    PRIMARY KEY (PRD_CODIGO),
    FOREIGN KEY (PRD_CATEG) REFERENCES CATEGORIAS(CTG_CODIGO),
    FOREIGN KEY (PRD_FORN) REFERENCES FORNECEDORES(FRN_CODIGO)
);
    
SELECT * FROM CATEGORIAS;
