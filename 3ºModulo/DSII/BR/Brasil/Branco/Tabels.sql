CREATE DATABASE BRASIL;
USE BRASIL;
 -- drop database brasil;
CREATE TABLE `ESTADOS`(
  `EST_SIGLA` varchar(2) NOT NULL,
  `EST_NOME` varchar(150) DEFAULT NULL,
  `EST_REGIAO` varchar(50) DEFAULT NULL,
  PRIMARY KEY (`EST_SIGLA`)
  
) ENGINE=INNODB DEFAULT CHARSET=latin1;
CREATE TABLE `CIDADE`(
  `CID_COD` int(11) NOT NULL AUTO_INCREMENT,
  `CID_NOME` varchar(150) DEFAULT NULL,
  `CID_ESTADO` varchar(2) NOT NULL,
  `CID_POPULACAO` bigint(20) DEFAULT NULL,
  cid_capital bool default 0,
  PRIMARY KEY (`CID_COD`),
  CONSTRAINT FK_ESTCID FOREIGN KEY(CID_ESTADO) REFERENCES ESTADOS(EST_SIGLA)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=latin1;

create table Turismo(
TUR_COD int(11) Not Null auto_increment,
TUR_NOME VARCHAR(150) DEFAULT NULL,
TUR_ESTADO VARCHAR(2) NOT NULL,
TUR_CIDADE varchar(150) default NULL,
PRIMARY KEY (TUR_COD) ,
constraint FK_ESTTUR foreign key(TUR_ESTADO) references ESTADOS(EST_SIGLA),
constraint FK_CIDTUR foreign key(TUR_CIDADE) references CIDADE(CID_NOME));


